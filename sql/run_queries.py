"""Runs every query in queries.sql against data/retail.db.

Writes sql/results.md and dashboard/sql.html (the same outputs, for the live site).
Standard library only: python sql/run_queries.py
Other folders for a test run: python sql/run_queries.py --db <file.db> --out-dir <folder>
(then results.md and sql.html are written into that folder instead).
"""
import argparse
import html
import sqlite3
from pathlib import Path

HERE = Path(__file__).parent
DB = HERE.parent / "data" / "retail.db"
MAX_ROWS = 15

parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
parser.add_argument("--db", type=Path, default=DB, help="SQLite file built by the notebook")
parser.add_argument("--out-dir", type=Path, default=None, help="write results.md and sql.html here instead")
args = parser.parse_args()
RESULTS_PATH = (args.out_dir or HERE) / "results.md"
PAGE_PATH = (args.out_dir or HERE.parent / "dashboard") / "sql.html"


def fmt(v, col):
    if v is None:
        return "NULL"
    if isinstance(v, float):
        return f"{v:,.2f}"
    return f"{v:,}" if isinstance(v, int) and not col.endswith("_id") else str(v)


blocks = (HERE / "queries.sql").read_text(encoding="utf-8").split("-- Q")[1:]
con = sqlite3.connect(args.db)
md = ["# SQL query outputs", "", "Generated by `python sql/run_queries.py` from `data/retail.db`.", ""]
page = []
for block in blocks:
    title, sql = block.split("\n", 1)
    sql = sql.strip()
    cur = con.execute(sql)
    cols = [d[0] for d in cur.description]
    rows = cur.fetchall()
    shown = rows[:MAX_ROWS]
    more = f"... {len(rows) - MAX_ROWS} more rows" if len(rows) > MAX_ROWS else ""
    print(f"Q{title}: {len(rows)} rows")

    md += [f"## Q{title}", "", "```sql", sql, "```", "",
           "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    md += ["| " + " | ".join(fmt(v, c) for v, c in zip(r, cols)) + " |" for r in shown]
    md += [more, ""] if more else [""]

    head = "".join(f"<th>{html.escape(c)}</th>" for c in cols)
    body = "".join("<tr>" + "".join(f"<td>{html.escape(fmt(v, c))}</td>" for v, c in zip(r, cols)) + "</tr>" for r in shown)
    page.append(f"<section><h2>Q{html.escape(title)}</h2><pre><code>{html.escape(sql)}</code></pre>"
                f"<div class=\"scroll\"><table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table></div>"
                f"{f'<p>{more}</p>' if more else ''}</section>")

con.close()
RESULTS_PATH.parent.mkdir(parents=True, exist_ok=True)
RESULTS_PATH.write_text("\n".join(md), encoding="utf-8")
template = (HERE / "sql_page.html").read_text(encoding="utf-8")
PAGE_PATH.write_text(template.replace("<!--QUERIES-->", "\n".join(page)), encoding="utf-8")
print(f"wrote {RESULTS_PATH} and {PAGE_PATH}")
